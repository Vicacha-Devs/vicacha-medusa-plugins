import { model } from "@medusajs/framework/utils"
import {
  DIAN_DOCUMENT_STATUSES,
  DIAN_DOCUMENT_TYPES,
  DIAN_ENVIRONMENTS,
  DIAN_PAYMENT_FORMS,
  DIAN_PAYMENT_MEANS,
  DIAN_PROVIDER_TYPES,
} from "../../../types"

export const DianElectronicDocument = model
  .define("dian_electronic_document", {
    id: model.id({ prefix: "ddoc" }).primaryKey(),
    order_id: model.text(),
    customer_id: model.text().nullable(),
    company_id: model.text().nullable(),
    resolution_id: model.text(),
    related_document_id: model.text().nullable(),
    pdf_document_id: model.text().nullable(), // Linked document ID in @vicacha-devs/medusa-plugin-documents
    document_type: model.enum([...DIAN_DOCUMENT_TYPES]).default("01"),
    status: model.enum([...DIAN_DOCUMENT_STATUSES]).default("draft"),
    environment: model.enum([...DIAN_ENVIRONMENTS]).default("2"),
    provider: model.enum([...DIAN_PROVIDER_TYPES]).default("native_soap"),
    prefix: model.text(),
    consecutive: model.number(),
    document_number: model.text(),
    cufe_cude: model.text(),
    cufe_cude_algorithm: model.text().default("CUFE-SHA384"),
    software_security_code: model.text(),
    qr_url: model.text(),
    qr_data: model.text(),
    issue_date: model.text(),
    issue_time: model.text(),
    payment_form: model.enum([...DIAN_PAYMENT_FORMS]).default("1"),
    payment_means: model.enum([...DIAN_PAYMENT_MEANS]).default("10"),
    currency_code: model.text().default("COP"),
    line_extension_amount: model.float().default(0),
    tax_exclusive_amount: model.float().default(0),
    tax_inclusive_amount: model.float().default(0),
    allowance_total_amount: model.float().default(0),
    charge_total_amount: model.float().default(0),
    payable_amount: model.float().default(0),
    tax_breakdown: model.json().nullable(),
    withholding_breakdown: model.json().nullable(),
    seller_snapshot: model.json().nullable(),
    buyer_snapshot: model.json().nullable(),
    resolution_snapshot: model.json().nullable(),
    discrepancy_concept_code: model.text().nullable(),
    discrepancy_description: model.text().nullable(),
    xml_signed: model.text().nullable(),
    application_response_xml: model.text().nullable(),
    attached_document_xml: model.text().nullable(),
    zip_filename: model.text().nullable(),
    zip_base64: model.text().nullable(),
    dian_track_id: model.text().nullable(),
    dian_status_code: model.text().nullable(),
    dian_status_message: model.text().nullable(),
    dian_errors: model.json().nullable(),
    retry_count: model.number().default(0),
    validated_at: model.dateTime().nullable(),
    audit_log: model.json().nullable(),
    metadata: model.json().nullable(),
  })
  .indexes([
    {
      name: "IDX_dian_doc_order_id",
      on: ["order_id"],
      where: "deleted_at IS NULL",
    },
    {
      name: "IDX_dian_doc_cufe",
      on: ["cufe_cude"],
      unique: true,
      where: "deleted_at IS NULL",
    },
    {
      name: "IDX_dian_doc_number",
      on: ["document_number"],
      where: "deleted_at IS NULL",
    },
  ])
